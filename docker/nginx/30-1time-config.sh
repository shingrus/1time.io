#!/bin/sh
# Writes the env-driven nginx config (visitor IP, rate limits) into /etc/nginx/1time/
# at container start. The variables are documented in README.md and .env.example.
set -eu

OUT_DIR=/etc/nginx/1time

# The default trust list. Never all private ranges: internal users could then fake their IP.
# No `^` in the awk: busybox builds without math support reject it.
own_networks() {
    [ -r /proc/net/route ] && awk 'function hex(s,  i, n) { n = 0; for (i = 1; i <= length(s); i++) n = n * 16 + index("0123456789ABCDEF", toupper(substr(s, i, 1))) - 1; return n }
         NR > 1 && $1 != "lo" && $2 != "00000000" && $3 == "00000000" {
             d = $2; m = hex($8); bits = 0
             while (m > 0) { bits += m % 2; m = int(m / 2) }
             printf "%d.%d.%d.%d/%d\n", hex(substr(d, 7, 2)), hex(substr(d, 5, 2)), hex(substr(d, 3, 2)), hex(substr(d, 1, 2)), bits
         }' /proc/net/route
    # if_inet6 fields: address, ifindex, prefix length, scope (00 = global), flags, name.
    [ -r /proc/net/if_inet6 ] && awk 'function hex(s,  i, n) { n = 0; for (i = 1; i <= length(s); i++) n = n * 16 + index("0123456789ABCDEF", toupper(substr(s, i, 1))) - 1; return n }
         $6 != "lo" && $4 == "00" {
             len = hex($3); out = ""
             for (i = 0; i < 32; i++) {
                 v = hex(substr($1, i + 1, 1)); keep = len - i * 4
                 if (keep <= 0) v = 0
                 else if (keep < 4) { step = (keep == 1) ? 8 : (keep == 2) ? 4 : 2; v = int(v / step) * step }
                 out = out sprintf("%x", v)
                 if (i % 4 == 3 && i < 31) out = out ":"
             }
             print out "/" len
         }' /proc/net/if_inet6
    return 0
}

fail() {
    echo "30-1time-config.sh: $*" >&2
    exit 1
}

rate() {
    eval "value=\${$1:-$2}"
    printf '%s' "$value" | grep -Eq '^[1-9][0-9]*r/[sm]$' \
        || fail "$1='$value' is not a rate like 45r/m or 2r/s"
    printf '%s' "$value"
}

mkdir -p "$OUT_DIR"

real_ip_header="${REAL_IP_HEADER:-X-Forwarded-For}"
printf '%s' "$real_ip_header" | grep -Eq '^[A-Za-z0-9-]+$' \
    || fail "REAL_IP_HEADER='$real_ip_header' is not a header name"

trusted="${TRUSTED_PROXIES:-}"
if [ -z "$trusted" ]; then
    trusted=$(own_networks | sort -u | tr '\n' ' ' | sed 's/ $//')
    [ -n "$trusted" ] || trusted="none"
fi
{
    echo "# Generated by 30-1time-config.sh at container start; do not edit."
    if [ "$trusted" != "none" ]; then
        for proxy in $(printf '%s' "$trusted" | tr ',' ' '); do
            printf '%s' "$proxy" | grep -Eq '^[0-9A-Fa-f:.]+(/[0-9]{1,3})?$' \
                || fail "TRUSTED_PROXIES entry '$proxy' is not an address or CIDR"
            echo "set_real_ip_from $proxy;"
        done
        echo "real_ip_header $real_ip_header;"
        echo "real_ip_recursive on;"
    fi
} > "$OUT_DIR/real-ip.conf"

limit_file() {
    if [ "$rate_limit" = "on" ]; then
        echo "$2" > "$OUT_DIR/$1"
    else
        echo "# RATE_LIMIT=off" > "$OUT_DIR/$1"
    fi
}

rate_limit="${RATE_LIMIT:-on}"
case "$rate_limit" in
    on|off) ;;
    *) fail "RATE_LIMIT='$rate_limit' must be on or off" ;;
esac

# Assignments, not inline in echo: only then does a failing $(...) stop the script.
write_rate=$(rate RATE_LIMIT_WRITE 45r/m)
upload_rate=$(rate RATE_LIMIT_UPLOAD 120r/m)
read_rate=$(rate RATE_LIMIT_READ 60r/m)

{
    echo "# Generated by 30-1time-config.sh at container start; do not edit."
    if [ "$rate_limit" = "on" ]; then
        echo "limit_req_zone \$binary_remote_addr zone=api_write:10m rate=$write_rate;"
        echo "limit_req_zone \$binary_remote_addr zone=api_upload:10m rate=$upload_rate;"
        echo "limit_req_zone \$binary_remote_addr zone=api_read:10m rate=$read_rate;"
        echo "limit_req_zone \$binary_remote_addr zone=api_stats:10m rate=240r/m;"
        echo "limit_req_status 429;"
    fi
} > "$OUT_DIR/limit-zones.conf"

limit_file limit-write.conf  "limit_req zone=api_write burst=10 nodelay;"
# A 250 MB file is 63 chunk requests; the burst lets one go up unthrottled.
limit_file limit-upload.conf "limit_req zone=api_upload burst=63 nodelay;"
limit_file limit-read.conf   "limit_req zone=api_read burst=15 nodelay;"
limit_file limit-stats.conf  "limit_req zone=api_stats burst=30 nodelay;"

echo "30-1time-config.sh: rate limits $rate_limit, trusted proxies: $trusted"
